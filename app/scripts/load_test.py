"""Latency test against the RUNNING server: 20 sequential + 3 rounds x 5 concurrent /parse calls.

    python -m app.scripts.load_test [--base-url http://127.0.0.1:8001] [--no-write]

Prints p50/p95/max and error count; writes a "Last load test" section into docs/operations.md.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import re
import sys
import time
from datetime import datetime

import httpx

from app.core.config import PROJECT_ROOT

QUERIES = [
    "Oliy ma'lumotli, 30 yoshdan katta ayollar",
    "Samarqand viloyatidagi 25-40 yoshli davlat xizmatchilari",
    "Женщины старше 30 лет с высшим образованием",
    "Familiyasi Karimov, ismi Ali",
    "bo'lim boshliqlari va direktorlar",
]
SECTION = "## Last load test"


def _pct(values: list[float], q: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    return s[min(len(s) - 1, int(round(q * (len(s) - 1))))]


async def _call(client: httpx.AsyncClient, query: str, headers: dict) -> tuple[float, bool]:
    t0 = time.perf_counter()
    try:
        r = await client.post("/api/v1/ai-search/parse", json={"query": query}, headers=headers)
        ok = r.status_code == 200
    except httpx.HTTPError:
        ok = False
    return (time.perf_counter() - t0) * 1000, ok


async def run(base_url: str) -> dict:
    headers = {"X-API-Key": os.environ["AI_SEARCH_API_KEY"]} if os.environ.get("AI_SEARCH_API_KEY") else {}
    seq: list[float] = []
    conc: list[float] = []
    errors = 0
    async with httpx.AsyncClient(base_url=base_url, timeout=600) as client:
        for i in range(20):
            ms, ok = await _call(client, QUERIES[i % len(QUERIES)], headers)
            seq.append(ms)
            errors += not ok
            print(f"seq {i + 1:2}/20 {ms:8.0f} ms {'ok' if ok else 'ERROR'}", flush=True)
        for rnd in range(3):
            t0 = time.perf_counter()
            results = await asyncio.gather(*[_call(client, q, headers) for q in QUERIES])
            for ms, ok in results:
                conc.append(ms)
                errors += not ok
            print(f"concurrent round {rnd + 1}/3: 5 calls in {(time.perf_counter() - t0) * 1000:.0f} ms", flush=True)
    return {"seq": seq, "conc": conc, "errors": errors}


def render(res: dict, base_url: str) -> str:
    seq, conc, allv = res["seq"], res["conc"], res["seq"] + res["conc"]
    return "\n".join([
        SECTION,
        "",
        f"_Generated by `python -m app.scripts.load_test` at {datetime.now().isoformat(timespec='seconds')} "
        f"against {base_url}._",
        "",
        "| Series | Calls | p50 ms | p95 ms | max ms |",
        "|---|---|---|---|---|",
        f"| Sequential | {len(seq)} | {_pct(seq, .5):.0f} | {_pct(seq, .95):.0f} | {max(seq):.0f} |",
        f"| Concurrent (3 x 5) | {len(conc)} | {_pct(conc, .5):.0f} | {_pct(conc, .95):.0f} | {max(conc):.0f} |",
        f"| All | {len(allv)} | {_pct(allv, .5):.0f} | {_pct(allv, .95):.0f} | {max(allv):.0f} |",
        "",
        f"Errors: **{res['errors']}**. Concurrent calls queue behind the single-model lock, so their latency "
        "includes waiting time (expected with one worker).",
        "",
    ])


def write_section(text: str) -> None:
    path = PROJECT_ROOT / "docs" / "operations.md"
    doc = path.read_text(encoding="utf-8") if path.exists() else "# Operations\n\n"
    pattern = re.compile(rf"{re.escape(SECTION)}\n.*?(?=\n## |\Z)", re.DOTALL)
    doc = pattern.sub(text.rstrip() + "\n", doc) if SECTION in doc else doc.rstrip() + "\n\n" + text
    path.write_text(doc, encoding="utf-8", newline="\n")  # keep LF on Windows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-url", default="http://127.0.0.1:8001")
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args(argv)
    res = asyncio.run(run(args.base_url))
    text = render(res, args.base_url)
    print(text)
    if not args.no_write:
        write_section(text)
    return 1 if res["errors"] else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
